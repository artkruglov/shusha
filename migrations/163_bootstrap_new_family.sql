-- Код создания семьи для установки, у которой уже есть владелец.
--
-- До сих пор bootstrap-код создавал только первого владельца: при существующем владельце скрипт отказывал, а канал
-- отвечал «настроено». Для бета-семей друзей в той же установке нужен второй вид кода: он создаёт новую семью с
-- новым владельцем и никого не затрагивает. Вид задаёт оператор флагом `--new-family` при выдаче кода; обычный код
-- по-прежнему создаёт семью только пока владельца нет.
ALTER TABLE bootstrap_codes ADD COLUMN new_family boolean NOT NULL DEFAULT false;
