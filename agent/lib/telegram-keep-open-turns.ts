/**
 * Ход, итог которого не сворачивается под «Полный ответ».
 *
 * Exports:
 * - `markTelegramKeepOpen`, `takeTelegramKeepOpen`: флаг на ход (ключ сессия и ход Eve).
 *
 * Итог записи или закрытия дел (`filed`, `notice`) человек должен видеть, а не искать под катом
 * (1 октября 2026 весь перечень «записано / не закрылось» ушёл под «Полный ответ» после первой
 * фразы). Директиву раньше вкладывали в текст ответа инструмента, и в эвале модель то пересказывала
 * строки, то оборачивала их парой тегов: из десяти ходов директива дошла как надо не всегда. Теперь
 * инструмент только ставит флаг, а канал сам добавляет директиву к готовому ответу хода.
 *
 * Состояние в памяти процесса, как у отбивок: перезапуск теряет флаг одного хода, и тогда длинный
 * ответ сворачивается по обычному правилу. Лишние ключи не копятся: флаг снимается при доставке, а
 * запас ограничен.
 */
const MAX_MARKED_TURNS = 500;
const marked = new Set<string>();

export function markTelegramKeepOpen(key: string): void {
  if (marked.size >= MAX_MARKED_TURNS) marked.delete(marked.values().next().value as string);
  marked.add(key);
}

/** Снимает флаг и говорит, стоял ли он; повторный вызов для того же хода вернёт `false`. */
export function takeTelegramKeepOpenMark(key: string): boolean {
  return marked.delete(key);
}
